type Publisher struct {
	cfg   Config
	stats *RuntimeStats

	client mqtt.Client

	mu        sync.Mutex
	lastState AlarmState
	lastCode  string
	lastUser  string

	// Serializes publishDiscoveryConfig so OnConnect and the post-Connect
	// fallback in Connect() cannot both race past the discoverySent check.
	discoveryMu sync.Mutex
	// True once discovery has been published successfully on this connection.
	// Reset to false on connection loss so reconnect republishes it.
	discoverySent atomic.Bool

	// connectCount counts successful (re)connects. The first connect is 1;
	// values > 1 indicate a reconnect (incremented in OnConnect).
	connectCount atomic.Uint64
}

func (p *Publisher) discoveryConfigTopic() string {
	// homeassistant/sensor/<node_id>/<object_id>/config
	return fmt.Sprintf("%s/sensor/%s/%s/config",
		strings.TrimSuffix(p.cfg.MQTTDiscoveryPrefix, "/"),
		p.cfg.MQTTDiscoveryNodeID,
		p.cfg.MQTTDiscoveryObject,
	)
}

func (p *Publisher) userDiscoveryConfigTopic() string {
	// homeassistant/sensor/<node_id>/user/config
	return fmt.Sprintf("%s/sensor/%s/user/config",
		strings.TrimSuffix(p.cfg.MQTTDiscoveryPrefix, "/"),
		p.cfg.MQTTDiscoveryNodeID,
	)
}

func (p *Publisher) uniqueID() string {
	return fmt.Sprintf("%s_%s", p.cfg.MQTTDiscoveryNodeID, p.cfg.MQTTDiscoveryObject)
}

func (p *Publisher) userTopic() string {
	return p.cfg.MQTTBaseTopic + "/user"
}

func (p *Publisher) publishDiscoveryConfig() {
	if !p.cfg.MQTTDiscoveryEnable {
		return
	}
	// Serialize against concurrent callers (OnConnect callback + main thread
	// Connect() fallback). Without this, both can pass the discoverySent
	// check and publish twice.
	p.discoveryMu.Lock()
	defer p.discoveryMu.Unlock()
	if p.discoverySent.Load() {
		return
	}
	if p.client == nil || !p.client.IsConnected() {
		return
	}

	// 1. Publish STATE sensor discovery
	statePayload := map[string]any{
		"name":                  p.cfg.MQTTDiscoveryName,
		"unique_id":             p.uniqueID(),
		"state_topic":           p.cfg.MQTTTopic,
		"availability_topic":    p.cfg.MQTTAvailabilityTopic,
		"payload_available":     p.cfg.MQTTAvailabilityOn,
		"payload_not_available": p.cfg.MQTTAvailabilityOff,
		"value_template":        `{{ value_json.state }}`,
		"device_class":          "enum",
		"options":               []string{string(StateUnknown), string(StateDisarmed), string(StateArmed), string(StateNight), string(StateAlarm)},
		"icon":                  "mdi:shield-home",

		"device": map[string]any{
			"identifiers":  []string{"sia2mqtt_ajax"},
			"name":         "sia2mqtt Ajax",
			"manufacturer": "Custom",
			"model":        "SIA DC-09 Receiver",
		},
	}

	stateBody, err := json.Marshal(statePayload)
	if err != nil {
		log.Printf("[%s] MQTT discovery: failed to marshal state payload: %v\n", time.Now().Format("15:04:05"), err)
		return
	}
	stateTopic := p.discoveryConfigTopic()
	t1 := p.client.Publish(stateTopic, p.cfg.MQTTQOS, true, stateBody)
	t1.Wait()
	if t1.Error() == nil {
		log.Printf("[%s] MQTT discovery (state) published: %s\n", time.Now().Format("15:04:05"), stateTopic)
	} else {
		log.Printf("[%s] MQTT discovery (state) publish error: %v\n", time.Now().Format("15:04:05"), t1.Error())
		return
	}

	// 2. Publish USER sensor discovery
	userPayload := map[string]any{
		"name":                  p.cfg.MQTTDiscoveryName + " Last User",
		"unique_id":             p.uniqueID() + "_user",
		"state_topic":           p.userTopic(),
		"availability_topic":    p.cfg.MQTTAvailabilityTopic,
		"payload_available":     p.cfg.MQTTAvailabilityOn,
		"payload_not_available": p.cfg.MQTTAvailabilityOff,
		"value_template":        `{{ value_json.user }}`,
		"icon":                  "mdi:account",

		"device": map[string]any{
			"identifiers":  []string{"sia2mqtt_ajax"},
			"name":         "sia2mqtt Ajax",
			"manufacturer": "Custom",
			"model":        "SIA DC-09 Receiver",
		},
	}

	userBody, err := json.Marshal(userPayload)
	if err != nil {
		log.Printf("[%s] MQTT discovery: failed to marshal user payload: %v\n", time.Now().Format("15:04:05"), err)
		return
	}
	userTopic := p.userDiscoveryConfigTopic()
	t2 := p.client.Publish(userTopic, p.cfg.MQTTQOS, true, userBody)
	t2.Wait()
	if t2.Error() == nil {
		log.Printf("[%s] MQTT discovery (user) published: %s\n", time.Now().Format("15:04:05"), userTopic)
		p.discoverySent.Store(true)
	} else {
		log.Printf("[%s] MQTT discovery (user) publish error: %v\n", time.Now().Format("15:04:05"), t2.Error())
	}
}

func (p *Publisher) Connect() error {
	opts := mqtt.NewClientOptions()
	opts.AddBroker(p.cfg.MQTTBroker)

	clientID := p.cfg.MQTTClientID
	if clientID == "" {
		clientID = fmt.Sprintf("sia2mqtt-%d", time.Now().UnixNano())
	}
	opts.SetClientID(clientID)

	if p.cfg.MQTTUser != "" {
		opts.SetUsername(p.cfg.MQTTUser)
		opts.SetPassword(p.cfg.MQTTPass)
	}

	opts.SetAutoReconnect(true)
	opts.SetConnectRetry(true)
	opts.SetConnectRetryInterval(3 * time.Second)
	opts.SetKeepAlive(30 * time.Second)
	opts.SetPingTimeout(10 * time.Second)

	if strings.HasPrefix(strings.ToLower(p.cfg.MQTTBroker), "tls://") || strings.HasPrefix(strings.ToLower(p.cfg.MQTTBroker), "ssl://") {
		tlsCfg := &tls.Config{InsecureSkipVerify: p.cfg.MQTTInsecureSkipVerify}
		opts.SetTLSConfig(tlsCfg)
	}

	if p.cfg.MQTTAvailabilityTopic != "" {
		opts.SetWill(p.cfg.MQTTAvailabilityTopic, p.cfg.MQTTAvailabilityOff, p.cfg.MQTTQOS, true)
	}

	opts.OnConnect = func(c mqtt.Client) {
		n := p.connectCount.Add(1)
		if n > 1 {
			atomic.AddUint64(&p.stats.MQTTReconnects, 1)
			log.Printf("[%s] MQTT reconnected (count=%d)\n", time.Now().Format("15:04:05"), n)
		}
		if p.cfg.MQTTAvailabilityTopic != "" {
			t := c.Publish(p.cfg.MQTTAvailabilityTopic, p.cfg.MQTTQOS, true, p.cfg.MQTTAvailabilityOn)
			t.Wait()
		}
		// Publish discovery config on (re)connect
		p.publishDiscoveryConfig()
		// Republish current state/user so the broker has fresh values even if
		// retained messages were lost (broker restart) or new subscribers came
		// online while we were disconnected.
		p.RepublishCurrent()
	}

	opts.OnConnectionLost = func(_ mqtt.Client, err error) {
		log.Printf("[%s] MQTT connection lost: %v\n", time.Now().Format("15:04:05"), err)
		p.discoverySent.Store(false)
	}

	p.client = mqtt.NewClient(opts)
	tok := p.client.Connect()
	tok.Wait()
	if err := tok.Error(); err != nil {
		return err
	}

	log.Printf("[%s] MQTT connected as %s to %s\n", time.Now().Format("15:04:05"), clientID, sanitizeBrokerURL(p.cfg.MQTTBroker))
	// Ensure discovery is published even if OnConnect already fired
	p.publishDiscoveryConfig()
	return nil
}

func (p *Publisher) IsConnected() bool {
	return p.client != nil && p.client.IsConnected()
}

// publishStateMessage publishes the state JSON to the MQTT broker without any
// dedup logic. Returns nil on success. The publisher mutex is NOT held while
// the network round-trip completes.
func (p *Publisher) publishStateMessage(state AlarmState, code string) error {
	if p.client == nil || !p.client.IsConnected() {
		return errors.New("mqtt not connected")
	}
	msg := map[string]any{
		"state": string(state),
		"code":  code,
		"ts":    time.Now().Format(time.RFC3339),
	}
	body, err := json.Marshal(msg)
	if err != nil {
		return fmt.Errorf("marshal state payload: %w", err)
	}
	t := p.client.Publish(p.cfg.MQTTTopic, p.cfg.MQTTQOS, p.cfg.MQTTRetain, body)
	t.Wait()
	if err := t.Error(); err != nil {
		return err
	}
	log.Printf("[%s] MQTT publish: topic=%s payload=%s\n", time.Now().Format("15:04:05"), p.cfg.MQTTTopic, string(body))
	return nil
}

// publishUserMessage publishes the user JSON to the user topic without dedup.
func (p *Publisher) publishUserMessage(userID string) error {
	if p.client == nil || !p.client.IsConnected() {
		return errors.New("mqtt not connected")
	}
	msg := map[string]any{
		"user": userID,
		"ts":   time.Now().Format(time.RFC3339),
	}
	body, err := json.Marshal(msg)
	if err != nil {
		return fmt.Errorf("marshal user payload: %w", err)
	}
	userTopic := p.userTopic()
	t := p.client.Publish(userTopic, p.cfg.MQTTQOS, p.cfg.MQTTRetain, body)
	t.Wait()
	if err := t.Error(); err != nil {
		return err
	}
	log.Printf("[%s] MQTT user publish: topic=%s payload=%s\n", time.Now().Format("15:04:05"), userTopic, string(body))
	return nil
}

// PublishState dedups against the last successful publish, then publishes.
// Crucially the dedup state is only updated AFTER the publish succeeds —
// otherwise a failed publish (e.g. broker disconnected) would poison the
// cache and the next identical event would be silently dropped.
//
// Publishes JSON to mqtt_topic:
//
//	{"state":"armed","code":"CL","ts":"2026-01-30T22:22:14+01:00"}
func (p *Publisher) PublishState(state AlarmState, code string) {
	p.mu.Lock()
	skip := state == p.lastState && code == p.lastCode
	p.mu.Unlock()
	if skip {
		return
	}

	if err := p.publishStateMessage(state, code); err != nil {
		log.Printf("[%s] MQTT publish error: state=%s code=%s err=%v\n", time.Now().Format("15:04:05"), state, code, err)
		p.stats.UpdateMQTTPublish(false)
		return
	}

	p.mu.Lock()
	p.lastState = state
	p.lastCode = code
	p.mu.Unlock()
	p.stats.UpdateMQTTPublish(true)
}

// PublishUser dedups against the last successful user publish, then publishes.
// Like PublishState, dedup state is only updated AFTER publish success.
//
// Publishes JSON to user topic:
//
//	{"user":"502","ts":"2026-01-30T22:22:14+01:00"}
func (p *Publisher) PublishUser(userID string) {
	p.mu.Lock()
	skip := userID == p.lastUser
	p.mu.Unlock()
	if skip {
		return
	}

	if err := p.publishUserMessage(userID); err != nil {
		log.Printf("[%s] MQTT user publish error: user=%s err=%v\n", time.Now().Format("15:04:05"), userID, err)
		return
	}

	p.mu.Lock()
	p.lastUser = userID
	p.mu.Unlock()
}

// RepublishCurrent re-publishes the current alarm state and last user from
// RuntimeStats, bypassing dedup. Called on (re)connect so the broker has the
// latest values even if its retained messages were lost (broker restart) or
// new subscribers came online during a disconnect.
func (p *Publisher) RepublishCurrent() {
	snap := p.stats.Snapshot()
	if snap.State == "" {
		return
	}
	if err := p.publishStateMessage(snap.State, snap.Code); err != nil {
		log.Printf("[%s] MQTT republish state error: %v\n", time.Now().Format("15:04:05"), err)
		p.stats.UpdateMQTTPublish(false)
	} else {
		p.mu.Lock()
		p.lastState = snap.State
		p.lastCode = snap.Code
		p.mu.Unlock()
		p.stats.UpdateMQTTPublish(true)
	}
	if snap.User != "" {
		if err := p.publishUserMessage(snap.User); err != nil {
			log.Printf("[%s] MQTT republish user error: %v\n", time.Now().Format("15:04:05"), err)
		} else {
			p.mu.Lock()
			p.lastUser = snap.User
			p.mu.Unlock()
		}
	}
}

// Shutdown publishes offline availability and disconnects the MQTT client.
func (p *Publisher) Shutdown() {
	if p.client == nil || !p.client.IsConnected() {
		return
	}
	if p.cfg.MQTTAvailabilityTopic != "" {
		t := p.client.Publish(p.cfg.MQTTAvailabilityTopic, p.cfg.MQTTQOS, true, p.cfg.MQTTAvailabilityOff)
		t.Wait()
	}
	p.client.Disconnect(1000)
}

// SyncFromStats initializes the dedup state from persisted RuntimeStats
// so the first duplicate event after restart is properly skipped.
func (p *Publisher) SyncFromStats(stats *RuntimeStats) {
	snap := stats.Snapshot()
	p.mu.Lock()
	defer p.mu.Unlock()
	p.lastState = snap.State
	p.lastCode = snap.Code
	p.lastUser = snap.User
}

